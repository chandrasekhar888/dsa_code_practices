package ArraysPractice;

public class Plusone {
    public static void main(String[] args) {
        int[] digits ={1,2,3,4};
        int result=0 ;
        for(int i=0;i<digits.length;i++){
           int sum = digits[i];
           result = sum;
           System.out.println(result);
        }

    }
}
